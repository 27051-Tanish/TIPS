namespace ExpenseTracker.Core.Model.Enum
{
    /// <summary>
    /// Defines the view menu for performing view operation.
    /// </summary>
    public enum ViewMenu
    {
        /// <summary>
        /// Represents the view operation of income record.
        /// </summary>
        IncomeRecord = 1,

        /// <summary>
        /// Represents the view operation of expense record.
        /// </summary>
        ExpenseRecord,

        /// <summary>
        /// Represents the view operation of entire record.
        /// </summary>
        EntireRecord,

        /// <summary>
        /// Represents the exit operation from the view menu.
        /// </summary>
        Exit,
    }
}
